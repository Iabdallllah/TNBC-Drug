"""Write a machine-readable validation summary after every pytest run.

The defence report reads `outputs_local/validation_status.json` instead of a
hand-typed test count.  A failing run is recorded as failing; it is never
silently promoted to green.
"""
import datetime as _dt
import json
import os


def pytest_sessionfinish(session, exitstatus):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, 'outputs_local', 'validation_status.json')
    total = int(getattr(session, 'testscollected', 0) or 0)
    failed = int(getattr(session, 'testsfailed', 0) or 0)
    payload = {
        'command': 'python -m pytest -q',
        'tests_total': total,
        'tests_failed': failed,
        'tests_passed': max(0, total - failed),
        'exitstatus': int(exitstatus),
        'status': 'PASS' if exitstatus == 0 and failed == 0 else 'FAIL',
        'finished_utc': _dt.datetime.now(_dt.timezone.utc).strftime('%Y-%m-%d %H:%M UTC'),
        'note': 'generated by tests/conftest.py; do not edit by hand',
    }
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as f:
        json.dump(payload, f, indent=2)
